class Employee {
  String name;
  String number;
  String position;
  String email;
  String phone;
  String address;
  String birthDate;
  String wage;
  String note;

  Employee({
    required this.name,
    required this.number,
    required this.position,
    required this.email,
    required this.phone,
    required this.address,
    required this.birthDate,
    required this.wage,
    required this.note,
  });
}
